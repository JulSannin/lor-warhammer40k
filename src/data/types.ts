/**
 * Схема данных сайта.
 *
 * Данные собираются из двух источников:
 *  1. content.generated.json — текст, разобранный из WARHAMMER_40K_LORE.md
 *     скриптом scripts/build-content.mjs. Машинный, не редактируется руками.
 *  2. meta.ts + images.ts — редакторский слой: эпохи, события таймлайна,
 *     акцентные цвета, картинки. Пишется руками.
 *
 * src/data/index.ts сшивает их в единый массив `sections`.
 */

/**
 * Текст с упрощённой inline-разметкой, унаследованной из markdown:
 * `**жирный**`, `*курсив*`, `[текст](#якорь)`.
 * Символ `\n` означает мягкий перенос строки внутри абзаца.
 */
export type RichText = string

export type Block =
  | { type: 'heading'; text: RichText; anchor: string }
  | { type: 'paragraph'; text: RichText }
  | { type: 'list'; ordered: boolean; items: RichText[] }
  | { type: 'table'; head: string[]; rows: RichText[][] }
  | { type: 'quote'; text: RichText }
  /** Абзац, помеченный в исходнике как `**[спорно]**` — лор противоречив. */
  | { type: 'disputed'; text: RichText }

/** Раздел в том виде, в каком его отдаёт парсер markdown. */
export interface ParsedSection {
  /** Стабильный латинский идентификатор, например `horus-heresy`. */
  id: string
  /** Якорь в стиле GitHub — чтобы ссылки внутри лора продолжали работать. */
  anchor: string
  /** Порядковый номер, 1…11. */
  index: number
  /** `ЧАСТЬ V` или null для разделов без нумерации. */
  part: string | null
  /** Заголовок без префикса части. */
  title: string
  /** Полный заголовок как в markdown. */
  fullTitle: string
  /** Короткое название для навигации, взятое из оглавления. */
  navLabel: string
  /** Датировка в скобках под заголовком, если есть. */
  subtitle: string | null
  blocks: Block[]
}

export interface GeneratedContent {
  docTitle: string
  epigraph: string | null
  sections: ParsedSection[]
}

/** Событие на ленте времени. */
export interface TimelineEvent {
  /** Как дата показывается человеку: `999.М41`, `~60 000 000 лет до н.э.` */
  date: string
  /**
   * Год для сортировки, в имперской шкале: (тысячелетие − 1) × 1000 + год.
   * `005.М31` → 30005, `999.М41` → 40999. Для доисторических — отрицательный.
   */
  year: number
  title: string
  /** Одно предложение сути. */
  summary: string
  /** Ключевые события выделяются на ленте. */
  major?: boolean
}

export interface SectionImage {
  /** Путь к локальной копии в public/img. */
  src: string
  /** Ссылка на исходник, по которой файл скачан. Нужна scripts/fetch-images.mjs. */
  remote: string
  alt: string
  caption: string
  /**
   * `hero` — крупный кадр в шапке раздела, `inline` — по ходу текста,
   * `primarch` — портрет для галереи примархов под таблицей легионов.
   */
  role: 'hero' | 'inline' | 'primarch'
  /** Для роли `primarch` — номер примарха римскими цифрами, как в таблице. */
  primarch?: string
  /**
   * Показывать целиком, а не обрезать по пропорции кадра. Нужно там, где
   * важна вся картинка: карта галактики с Цикатрикс Маледиктум при обрезке
   * теряет и заголовок, и легенду.
   */
  contain?: boolean
  /**
   * Подать как архивный лист: светлая подложка, рамка, поля. Нужно для
   * сканов из старых изданий — они нарисованы на белом, и на тёмной теме
   * без оформления выглядят вырвиглазным пятном.
   */
  plate?: boolean
  width: number
  height: number
  /**
   * Порядковый номер подзаголовка (`### …`) внутри раздела, после которого
   * встаёт картинка. Так четыре бога Хаоса попадают каждый под свой абзац,
   * а не туда, куда придётся. Без значения — картинка уходит в конец раздела.
   */
  afterHeading?: number
}

/** Редакторский слой поверх разобранного текста. */
export interface SectionMeta {
  /** Подпись эпохи для навигации и ленты: `М30 — М31`. */
  era: string
  /**
   * Позиция раздела на сквозной ленте времени.
   * null — раздел тематический (Хаос, Ксеносы, Главная мысль), вне хронологии.
   */
  year: number | null
  /** Одно предложение о разделе — показывается в навигации и под заголовком. */
  lead: string
  /** Акцентный цвет раздела (CSS-значение). */
  accent: string
  events: TimelineEvent[]
}

/**
 * Выжимка статьи русской вики: то, что показывает карточка по клику
 * на выделенном термине.
 *
 * Снимается при сборке скриптом scripts/fetch-wiki.mjs. Хранится в
 * проекте, а не запрашивается на лету: страница не делает ни одного
 * внешнего запроса, и карточка открывается мгновенно. Встроить саму
 * страницу вики во фрейм нельзя — Fandom это запрещает заголовком
 * X-Frame-Options.
 */
export interface WikiArticle {
  /** Название статьи на вики — может отличаться от термина в лоре. */
  title: string
  /** Первый содержательный абзац, обрезанный по границе предложения. */
  extract: string
  /** Имя файла в public/img/wiki, если у статьи есть заглавная картинка. */
  thumb?: string
  thumbWidth?: number
  thumbHeight?: number
  /**
   * Картинка нарисована на белом — фото миниатюры, схема, герб. Такую
   * показываем целиком на светлой подложке: обрезка рубит её пополам,
   * а на тёмной карточке белый фон бьёт по глазам.
   */
  lightThumb?: boolean
}

/**
 * Справка по термину: одна статья или несколько.
 *
 * Несколько — потому что часть терминов лора живёт сразу в двух местах
 * вики. «Стазис-гробницы» — это и статья о стазисе, и статья о некронах;
 * ни одна из них по отдельности термин не объясняет.
 */
export type WikiEntry = WikiArticle[]

/** Итоговый раздел: текст + редакторский слой + картинки. */
export interface Section extends ParsedSection, SectionMeta {
  images: SectionImage[]
  hero: SectionImage | null
  /**
   * Термин → номер блока, в котором он встречается в разделе впервые.
   * Кликабельно только первое упоминание: если подсвечивать все, текст
   * превращается в сплошную сеть ссылок.
   */
  wikiFirst: Record<string, number>
}
